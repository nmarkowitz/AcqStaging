"""Common motion-axis interface."""

from __future__ import annotations

from typing import Protocol, runtime_checkable

from acq_staging.models import ComponentIdentity, ComponentStatus, LimitsConfig


@runtime_checkable
class MotionAxis(Protocol):
    """Vendor-neutral interface used by services and the GUI."""

    def connect(self) -> None: ...

    def disconnect(self) -> None: ...

    def identity(self) -> ComponentIdentity: ...

    def identify(self) -> None: ...

    def status(self) -> ComponentStatus: ...

    def home(self) -> None: ...

    def stop(self) -> None: ...

    def move_absolute(self, destination: float) -> None: ...

    def move_relative(self, displacement: float) -> None: ...

    def get_position(self) -> float: ...

    def get_limits(self) -> LimitsConfig | None: ...
